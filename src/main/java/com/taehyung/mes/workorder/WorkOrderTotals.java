package com.taehyung.mes.workorder;

public class WorkOrderTotals {
    private Long resultCount;
    private java.math.BigDecimal producedQty;
    private java.math.BigDecimal goodQty;
    private java.math.BigDecimal defectQty;
    public Long getResultCount() { return resultCount; }
    public void setResultCount(Long resultCount) { this.resultCount = resultCount; }
    public java.math.BigDecimal getProducedQty() { return producedQty; }
    public void setProducedQty(java.math.BigDecimal producedQty) { this.producedQty = producedQty; }
    public java.math.BigDecimal getGoodQty() { return goodQty; }
    public void setGoodQty(java.math.BigDecimal goodQty) { this.goodQty = goodQty; }
    public java.math.BigDecimal getDefectQty() { return defectQty; }
    public void setDefectQty(java.math.BigDecimal defectQty) { this.defectQty = defectQty; }
}
